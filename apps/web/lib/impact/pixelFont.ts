/** Advance per character, in pixels of the 5×7 grid (5 + 1 spacing). */
export const ADVANCE = 6;
export const GLYPH_H = 7;

export function supported(ch: string): boolean {
  return ch === " " || ch.toUpperCase() in G;
}

/** Width in px of `text` at pixel size `px`. */
export function textWidth(text: string, px: number): number {
  return text.length === 0 ? 0 : (text.length * ADVANCE - 1) * px;
}

/** Largest pixel size ≤ `max` that fits `text` in `width`. */
export function fitPx(text: string, width: number, max: number): number {
  const n = Math.max(1, text.length * ADVANCE - 1);
  return Math.max(1, Math.min(max, Math.floor(width / n)));
}

/** SVG path data for `text` with its top-left at (x, y). */
export function textPath(text: string, x: number, y: number, px: number): string {
  const parts: string[] = [];
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const g = G[raw];
    if (g) {
      for (let row = 0; row < GLYPH_H; row++) {
        const line = g[row]!;
        for (let col = 0; col < 5; col++) {
          if (line[col] === "#") parts.push(`M${cx + col * px} ${y + row * px}h${px}v${px}h-${px}z`);
        }
      }
    }
    cx += ADVANCE * px;
  }
  return parts.join("");
}
